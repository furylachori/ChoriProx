class TestDefaultWorkspaceIncludesNull:
    """INT-004: get_actionable_tasks('default') includes NULL-workspace tasks."""

    def test_get_actionable_tasks_default_workspace_query(self):
        """Default workspace query should include NULL-workspace tasks.

        Verifies the Cypher query generated by get_actionable_tasks contains
        'IS NULL' when workspace_id ends with ':default', so tasks without a
        workspace_id are still returned.
        """
        from memory.task_graph import TaskGraph

        with patch("memory.task_graph.Neo4jClient") as mock_neo4j_cls:
            mock_neo4j = MagicMock()
            mock_neo4j_cls.return_value = mock_neo4j

            captured = {}
            def fake_execute_read(query, params=None, timeout=30):
                captured["query"] = query
                captured["params"] = params
                return []
            mock_neo4j._executor.execute_read.side_effect = fake_execute_read

            tg = TaskGraph()
            tg.get_actionable_tasks(
                status_filter=["pending", "in_progress", "complete"],
                workspace_id="test-session:default",
            )

        query_text = captured["query"]
        assert "IS NULL" in query_text, (
            "Default workspace query must include IS NULL check "
            "to include tasks without a workspace_id"
        )
        params = captured["params"]
        assert params["workspace_id"] == "test-session:default"


class TestUpdateTasksBatchStatus:
    """Tests for update_tasks_batch_status (Phase 3 new method)."""

    @staticmethod
    def _build_mock_neo4j(validation_records, update_records=None, reread_records=None, tx_exception=None):
        """Build a mock Neo4jClient with configured executor.execute_transaction.

        validation_records: list of dicts returned by validate query
        update_records: list of dicts returned by update query (or None to skip)
        reread_records: list of dicts returned by reread query (or None to skip)
        tx_exception: exception to raise from execute_transaction (overrides records)
        """
        mock_neo4j = MagicMock()

        if tx_exception is not None:
            mock_neo4j._executor.execute_transaction.side_effect = tx_exception
            return mock_neo4j

        mock_tx = MagicMock()

        results = []

        val_result = MagicMock()
        val_result.__iter__ = lambda self: iter(validation_records)
        val_result.consume.return_value = None
        results.append(val_result)

        if update_records is not None:
            upd_result = MagicMock()
            upd_result.__iter__ = lambda self: iter(update_records)
            upd_result.consume.return_value = None
            results.append(upd_result)

        if reread_records is not None:
            reread_result = MagicMock()
            reread_result.__iter__ = lambda self: iter(reread_records)
            reread_result.consume.return_value = None
            results.append(reread_result)

        mock_tx.run.side_effect = results
        mock_neo4j._executor.execute_transaction.side_effect = lambda fn: fn(mock_tx)

        return mock_neo4j

    def test_valid_batch_all_succeed(self):
        """All hashes resolve uniquely and transition successfully."""
        validation = [
            {"hash": "abc123", "current_status": "pending", "match_count": 1},
            {"hash": "def456", "current_status": "in_progress", "match_count": 1},
        ]
        update = [
            {"hash": "abc123", "updated": 1},
            {"hash": "def456", "updated": 1},
        ]
        mock_neo4j = self._build_mock_neo4j(validation, update)

        with patch("memory.task_graph.Neo4jClient", return_value=mock_neo4j):
            tg = TaskGraph()
            result = tg.update_tasks_batch_status(["abc123", "def456"], "complete", workspace_id="test_ws:default")

        assert len(result) == 2
        assert result[0] == {"hash": "abc123", "ok": True, "status": "complete", "changed": True}
        assert result[1] == {"hash": "def456", "ok": True, "status": "complete", "changed": True}

    def test_partial_failure_not_found_and_invalid_transition(self):
        """Mix of success, not_found, and invalid transition."""
        validation = [
            {"hash": "abc123", "current_status": "pending", "match_count": 1},
            {"hash": "notfound", "current_status": None, "match_count": 0},
            {"hash": "complete1", "current_status": "complete", "match_count": 1},
        ]
        update = [{"hash": "abc123", "updated": 1}]
        mock_neo4j = self._build_mock_neo4j(validation, update)

        with patch("memory.task_graph.Neo4jClient", return_value=mock_neo4j):
            tg = TaskGraph()
            result = tg.update_tasks_batch_status(
                ["abc123", "notfound", "complete1"], "complete", workspace_id="test_ws:default"
            )

        assert len(result) == 3
