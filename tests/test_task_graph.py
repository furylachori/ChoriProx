# ----------------------------------------------------------------------------
# C7: Regression tests for update_task_status (singular) OPTIONAL MATCH fix.
#
# The complete/invalid update queries use OPTIONAL MATCH (b:Bug)-[:RESOLVED_BY]->(t)
# to ensure the task status update succeeds even when no Bug is linked to
# the Task. Before the fix, an inner MATCH without a match would zero out
# the result rows, causing a false retry and (in worst case) leaving the
# status unchanged.
# ----------------------------------------------------------------------------


class TestUpdateTaskStatusOptionalMatch:
    """C7: update_task_status must succeed for tasks with NO linked Bug."""

    @staticmethod
    def _build_singular_mock_neo4j(count_records, update_records):
        """Build a mock Neo4jClient for the singular update_task_status path.

        update_task_status (singular) uses:
          - self._executor.execute_read  (count_query)
          - self._executor.execute_write (update_query with OPTIONAL MATCH)
        """
        mock_neo4j = MagicMock()
        mock_neo4j._executor.execute_read.return_value = count_records
        mock_neo4j._executor.execute_write.return_value = update_records
        return mock_neo4j

    def test_update_task_status_complete_succeeds_without_linked_bug(self):
        """Task with no Bug linked should transition to 'complete' and
        return ok=True. The OPTIONAL MATCH in the update query returns a
        null bug row, but count(t) still returns 1, so the update succeeds.
        """
        count_records = [{"cnt": 1, "current_status": "pending"}]
        update_records = [{"updated": 1}]
        mock_neo4j = self._build_singular_mock_neo4j(count_records, update_records)

        with patch("memory.task_graph.Neo4jClient", return_value=mock_neo4j):
            tg = TaskGraph()
            result = tg.update_task_status(
                "abc12345", "complete", workspace_id="ws:default",
            )

        assert result == {"ok": True, "status": "complete"}, (
            f"Task with no linked bug should transition to complete, got: {result}"
        )
        # OPTIONAL MATCH fix verification: the update query must use
        # OPTIONAL MATCH (not MATCH) so tasks without bugs still update.
        update_call = mock_neo4j._executor.execute_write.call_args
        update_query = update_call.args[0]
        assert "OPTIONAL MATCH" in update_query, (
            "update_query for 'complete' must use OPTIONAL MATCH so tasks "
            "without linked bugs are still updated"
        )
        assert "MATCH (b:Bug)-[:RESOLVED_BY]->(t)" in update_query, (
            "update_query must still target the Bug→Task relationship"
        )

    def test_update_task_status_invalid_succeeds_without_linked_bug(self):
        """Task with no Bug linked should transition to 'invalid' and
        return ok=True.
        """
        count_records = [{"cnt": 1, "current_status": "pending"}]
        update_records = [{"updated": 1}]
        mock_neo4j = self._build_singular_mock_neo4j(count_records, update_records)

        with patch("memory.task_graph.Neo4jClient", return_value=mock_neo4j):
            tg = TaskGraph()
            result = tg.update_task_status(
                "abc12345", "invalid", workspace_id="ws:default",
            )

        assert result == {"ok": True, "status": "invalid"}, (
            f"Task with no linked bug should transition to invalid, got: {result}"
        )
        update_call = mock_neo4j._executor.execute_write.call_args
        update_query = update_call.args[0]
        assert "OPTIONAL MATCH" in update_query, (
            "update_query for 'invalid' must use OPTIONAL MATCH so tasks "
            "without linked bugs are still updated"
        )
        # The 'invalid' path sets dismissal_reason; the OPTIONAL MATCH must
        # still wrap that SET so missing bugs don't crash the query.
        assert "b.dismissal_reason = 'task_invalidated'" in update_query

    def test_update_task_status_complete_with_linked_bug_resolves_bug(self):
        """Regression guard: when a Bug IS linked to the Task, the
        OPTIONAL MATCH finds it and sets b.status='resolved'. This is the
        original behavior the fix must preserve.
        """
        count_records = [{"cnt": 1, "current_status": "pending"}]
        update_records = [{"updated": 1}]
        mock_neo4j = self._build_singular_mock_neo4j(count_records, update_records)

        with patch("memory.task_graph.Neo4jClient", return_value=mock_neo4j):
            tg = TaskGraph()
            result = tg.update_task_status(
                "abc12345", "complete", workspace_id="ws:default",
            )

        assert result == {"ok": True, "status": "complete"}
        # The query must still SET b.status = 'resolved' so linked bugs
        # are transitioned atomically with the task.
        update_call = mock_neo4j._executor.execute_write.call_args
        update_query = update_call.args[0]
        assert "b.status = 'resolved'" in update_query, (
            "When a bug IS linked, the update query must still set "
            "b.status='resolved' (regression guard for atomic transition)"
        )